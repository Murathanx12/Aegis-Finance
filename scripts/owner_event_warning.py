"""PC saved SEC warning runner. Invoke with python -m scripts.owner_event_warning.

Preview prints sanitized per-event JSONL and never writes. --send requires an
existing private journal, an independent review JSON and an adoption JSON.
Review schema: {schema: owner-warning-review/1, independent_exact_source_review:
true, reviewer: nonempty string, sha256: {relative source path: exact byte hash},
adoption_sha256: exact adoption file hash}. Sources are exactly SOURCE_PATHS.
Adoption schema: {schema: owner-warning-adoption/3,
all_manual_deliveries_covered: true, suppressions: [{path: absolute private JSON
path, sha256: exact file hash}]}. The review binds exact adoption bytes. Each
suppression uses schema owner-warning-manual-suppression/1 and fields event_id,
ticker, accession, event_key, source_url, source_first_seen_utc, snapshot_clock,
snapshot_sha256, manual_source_row_sha256, corpus_line_sha256,
source_hashes_differ: true, tag_sha256, attempt_path, attempt_sha256, result_path,
result_sha256. Original proofs must be private and use the actual manual fallback
attempt/result schemas. Their byte hashes, clocks and native ACK bindings are
verified separately from adapter delivery. The known Apple proof hashes are
pinned below. Every known manual event needs a record, even after expiry; any
eligible matching event is suppressed, never represented as adapter text sent.
The reviewer attests completeness for additional manual events. New manual
warnings require new suppression records and a newly hash-bound adoption review.
No gate files or compatible adapter ACKs are generated by this runner.
Neither attestation is a cryptographic signature; trust its independent author.
No scheduling, forecast, quotes, trades, retries, or paid/model calls.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import time

from backend.services import owner_event_warning as adapter

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATHS = ('backend/services/owner_event_warning.py',
                'scripts/owner_event_warning.py', 'backend/services/telegram_bridge.py')

# Public-safe byte identities of the original manual evidence, read-only from R.
KNOWN_MANUAL_PROOFS = {
    'aapl-fy26q4-20261103-preopen': (
        'e99cca733416b4aa4e493d18ded460dba8c4b10716424196b3928ff189d3a9b8',
        'dcc2cef78603a3d8d0527fd0c684dcc944c9687920309f7407eaa7259d7645fe', 'AAPL'),
}


class Refused(ValueError):
    """Sanitized refusal code only."""


def read(path):
    path = Path(path).absolute()
    for part in (path, *path.parents):
        info = part.lstat()
        if stat.S_ISLNK(info.st_mode) or getattr(info, 'st_file_attributes', 0) & 0x400:
            raise Refused('REDIRECTED_INPUT')
    if not path.is_file() or path.stat().st_size > 32 * 1024 * 1024:
        raise Refused('INPUT_NOT_BOUNDED_FILE')
    return path.read_bytes()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def private_read(path):
    path = Path(path)
    if not path.is_absolute():
        raise Refused('ABSOLUTE_PRIVATE_PROOF_REQUIRED')
    adapter._journal_identity(path.parent)
    data = read(path)
    if os.name == 'nt':
        adapter._windows_private_acl(path)
    elif path.stat().st_mode & 0o077:
        raise Refused('PRIVATE_PROOF_REQUIRED')
    return data


def suppression_record(ref, *, now):
    raw = private_read(ref['path'])
    if sha(raw) != ref['sha256']:
        raise Refused('SUPPRESSION_HASH_MISMATCH')
    record = adapter._object(raw.decode('utf-8'))
    attempt_raw = private_read(record['attempt_path'])
    result_raw = private_read(record['result_path'])
    if (sha(attempt_raw) != record['attempt_sha256']
            or sha(result_raw) != record['result_sha256']):
        raise Refused('MANUAL_PROOF_HASH_MISMATCH')
    attempt = adapter._object(attempt_raw.decode('utf-8'))
    result = adapter._object(result_raw.decode('utf-8'))
    if record['event_id'] in KNOWN_MANUAL_PROOFS and (
            record['attempt_sha256'], record['result_sha256'], record['ticker']) != KNOWN_MANUAL_PROOFS[record['event_id']]:
        raise Refused('KNOWN_MANUAL_PROOF_MISMATCH')
    for key in ('snapshot_sha256', 'manual_source_row_sha256', 'corpus_line_sha256', 'tag_sha256'):
        if not isinstance(record[key], str) or not re.fullmatch('[0-9a-f]{64}', record[key]):
            raise Refused('INVALID_MANUAL_DIGEST')
    accession = record['accession']
    ticker = record['ticker']
    if (not isinstance(ticker, str) or not re.fullmatch(r'[A-Z]{1,5}(?:[.-][A-Z])?', ticker)
            or not re.fullmatch(r'\d{10}-\d{2}-\d{6}', accession)):
        raise Refused('INVALID_MANUAL_IDENTITY')
    url = re.fullmatch(r'https://www\.sec\.gov/Archives/edgar/data/(\d+)/(\d{18})/[A-Za-z0-9_-]+\.html?',
                       record['source_url'])
    if (not url or url[2] != accession.replace('-', '') or int(url[1]) != int(accession[:10])
            or record['event_key'] != adapter._digest({'ticker': ticker, 'accession': accession})
            or record['schema'] != 'owner-warning-manual-suppression/1'
            or attempt['schema'] != 'owner-warning-manual-fallback/1'
            or attempt['event_id'] != record['event_id'] or attempt['delivery'] != 'SENDING'
            or attempt['no_automatic_retry'] is not True
            or attempt['source_row_sha256'] != record['manual_source_row_sha256']
            or record['source_hashes_differ'] is not True
            or record['manual_source_row_sha256'] == record['corpus_line_sha256']
            or any(attempt[k] != record[k] for k in
                   ('source_url', 'source_first_seen_utc', 'snapshot_clock', 'snapshot_sha256'))
            or result['status'] != 'PLATFORM_ACKNOWLEDGED'
            or result['owner_read'] != 'UNVERIFIED'
            or not adapter._valid_ack(result['ack'], {
                'text_sha256': attempt['message_sha256'], 'tag_sha256': record['tag_sha256']})):
        raise Refused('MANUAL_PROOF_BINDING_MISMATCH')
    first = adapter._utc(attempt['source_first_seen_utc'])
    snapshot_clock = adapter._utc(attempt['snapshot_clock'])
    created = adapter._utc(attempt['created_utc'])
    observed = adapter._utc(result['observed_utc'])
    if not (first <= created <= observed <= now and snapshot_clock <= created):
        raise Refused('MANUAL_PROOF_CLOCK_INVALID')
    return record


def qualify_send(review_path, adoption_path, journal, *, now, artifacts=()):
    review = adapter._object(read(review_path).decode('utf-8'))
    adoption_bytes = read(adoption_path)
    adoption = adapter._object(adoption_bytes.decode('utf-8'))
    if (review.get('schema') != 'owner-warning-review/1'
            or review.get('independent_exact_source_review') is not True
            or not isinstance(review.get('reviewer'), str) or not review['reviewer'].strip()
            or review.get('sha256') != {p: sha(read(ROOT / p)) for p in SOURCE_PATHS}
            or review.get('adoption_sha256') != sha(adoption_bytes)
            or adoption.get('schema') != 'owner-warning-adoption/3'
            or adoption.get('all_manual_deliveries_covered') is not True
            or not isinstance(adoption.get('suppressions'), list)):
        raise Refused('REVIEW_OR_MANUAL_ADOPTION_REQUIRED')
    records = [suppression_record(ref, now=now) for ref in adoption['suppressions']]
    ids = [r['event_id'] for r in records]
    keys = [r['event_key'] for r in records]
    if (not set(KNOWN_MANUAL_PROOFS).issubset(ids)
            or len(set(ids)) != len(ids) or len(set(keys)) != len(keys)):
        raise Refused('MANUAL_SUPPRESSION_MISSING_OR_AMBIGUOUS')
    suppressed = set()
    for artifact in artifacts:
        for record in records:
            if artifact['event_key'] != record['event_key']:
                continue
            if (artifact['source_row_sha256'] != record['corpus_line_sha256']
                    or artifact['snapshot_sha256'] != record['snapshot_sha256']
                    or artifact['source_url'] != record['source_url']
                    or adapter._utc(artifact['captured_at']) != adapter._utc(record['source_first_seen_utc'])
                    or adapter._utc(artifact['snapshot_as_of']) != adapter._utc(record['snapshot_clock'])):
                raise Refused('MANUAL_CORPUS_BINDING_MISMATCH')
            suppressed.add(artifact['event_key'])
    adapter._journal_identity(journal)
    return suppressed


def run(*, ledger, snapshot, journal, now, send=False, review=None, adoption=None):
    """Return (exit code, sanitized receipts); all selection precedes sending."""
    receipts = []
    try:
        if now.utcoffset() != timedelta(0):
            raise Refused('UTC_REQUIRED')
        snapshot_bytes = read(snapshot)
        snap = adapter._object(snapshot_bytes.decode('utf-8'))
        stamp = adapter._utc(snap['t'])
        if not timedelta(0) <= now - stamp <= adapter.SNAPSHOT_MAX_AGE:
            raise Refused('SNAPSHOT_STALE_OR_FUTURE')
        positions = snap['positions']
        if not isinstance(positions, list) or not positions:
            raise Refused('NO_UNAMBIGUOUS_HOLDINGS')
        held = []
        for pos in positions:
            ticker = pos['symbol']
            if (not isinstance(ticker, str)
                    or not re.fullmatch(r'[A-Z]{1,5}(?:[.-][A-Z])?', ticker)
                    or ticker in held or adapter._number(pos['qty']) <= 0
                    or adapter._number(pos['market_value']) <= 0):
                raise Refused('AMBIGUOUS_HOLDINGS')
            held.append(ticker)
        base = Path(ledger) / 'news_corpus' / 'sec_edgar_8k_ex99_body'
        candidates = {ticker: [] for ticker in held}
        originals = {}
        for day in (now.date() - timedelta(days=1), now.date()):
            path = base / f'{day.isoformat()}.jsonl'
            if not path.exists():
                continue
            data = read(path)
            originals[path] = data
            for line in data.splitlines(keepends=True):
                if not line.strip():
                    continue
                row = adapter._object(line.decode('utf-8'))
                tickers = row.get('tickers')
                if (not isinstance(tickers, list) or not all(isinstance(t, str) for t in tickers)
                        or len(set(tickers)) != len(tickers)):
                    raise Refused('MALFORMED_CORPUS_TICKERS')
                for ticker in set(held).intersection(tickers):
                    if tickers != [ticker]:
                        raise Refused('AMBIGUOUS_SOURCE_TICKER')
                    candidates[ticker].append((path, line))
        if base / f'{now.date()}.jsonl' not in originals:
            raise Refused('NO_CURRENT_CORPUS')
        selected = []
        artifacts = []
        for ticker, matches in candidates.items():
            # Exact duplicate lines may recur across the two daily files.
            unique = {line: path for path, line in matches}
            if not unique:
                continue
            if len(unique) != 1:
                raise Refused('AMBIGUOUS_HELD_EVENT')
            line, path = next(iter(unique.items()))
            artifact = adapter.build_saved_warning(source_jsonl_path=path,
                pc_paper_snapshot_path=snapshot, ticker=ticker, now=now)
            receipt = {k: artifact[k] for k in ('event_key', 'source_row_sha256',
                'snapshot_sha256', 'status', 'reason') if k in artifact}
            receipt['at'] = now.isoformat()
            receipt['delivery'] = 'PREVIEW'
            receipts.append(receipt)
            if artifact['status'] != 'PROVISIONAL':
                raise Refused('MATERIAL_INPUT_REFUSED')
            selected.append((ticker, path, receipt))
            artifacts.append(artifact)
        if send:
            suppressed = qualify_send(review, adoption, journal, now=now, artifacts=artifacts)
            for _, _, receipt in selected:
                if receipt['event_key'] in suppressed:
                    receipt['delivery'] = 'SUPPRESSED_MANUAL'
            if all(receipt['delivery'] == 'SUPPRESSED_MANUAL' for _, _, receipt in selected):
                return 0, receipts
            # Import transport only after independent source/adoption qualification.
            from backend.services import telegram_bridge
            owner = telegram_bridge.owner_chat_id()
            if not isinstance(owner, str) or not re.fullmatch('[1-9][0-9]*', owner):
                raise Refused('PRIVATE_OWNER_REQUIRED')
            until = time.time() + 30
            def sender(text, *, tag):
                return telegram_bridge.send_owner_once(text, tag=tag,
                    expected_owner=owner, until=until)
        else:
            sender = None
        for ticker, path, receipt in selected:
            if read(snapshot) != snapshot_bytes or read(path) != originals[path]:
                raise Refused('INPUT_CHANGED')
            if send:
                suppressed = qualify_send(review, adoption, journal, now=now, artifacts=artifacts)
            if send and receipt['event_key'] in suppressed:
                receipt['delivery'] = 'SUPPRESSED_MANUAL'
                continue
            result = adapter.warn_saved(source_jsonl_path=path,
                pc_paper_snapshot_path=snapshot, ticker=ticker, now=now,
                journal_dir=journal, sender=sender)
            if result['artifact']['status'] != 'PROVISIONAL':
                raise Refused('MATERIAL_INPUT_REFUSED')
            receipt['delivery'] = result['delivery']
            if result['delivery'] not in ('NOT_SENT', 'SENT', 'ALREADY_SENT'):
                raise Refused('DELIVERY_RECONCILIATION_REQUIRED')
        return 0, receipts
    except (OSError, ValueError, TypeError, KeyError, AttributeError, UnicodeError):
        # Never print paths, raw input, exception text, account IDs or transport errors.
        receipts.append({'at': now.isoformat(), 'status': 'REFUSED',
                         'reason': 'RUN_REFUSED_REVIEW_INPUTS_AND_GATES'})
        return 2, receipts


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pc-paper-snapshot', type=Path, required=True,
                        help='Explicit caller-attested PC-PAPER saved snapshot')
    parser.add_argument('--journal-dir', type=Path, required=True,
                        help='Existing private persistent adapter journal; never auto-created')
    parser.add_argument('--send', action='store_true')
    parser.add_argument('--review', type=Path)
    parser.add_argument('--adoption', type=Path)
    args = parser.parse_args(argv)
    from backend import config
    code, receipts = run(ledger=config.OPTIMUS_LEDGER_DIR,
        snapshot=args.pc_paper_snapshot, journal=args.journal_dir,
        now=datetime.now(timezone.utc), send=args.send, review=args.review,
        adoption=args.adoption)
    for receipt in receipts:
        print(json.dumps(receipt, sort_keys=True))
    return code


if __name__ == '__main__':
    raise SystemExit(main())
