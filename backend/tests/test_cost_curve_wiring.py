def test_the_curve_charges_PER_NAME_and_the_receipt_says_what_it_charged():
    dv = np.array([2e6, 5e6, 2e7, 5e7, 3e8, 9e8, 1e9, 4e9])
    res = replay.run(_panel(dolvol=dv),
                     Policy(top_k=8, universe_n=8, holding_days=1000,
                            signal="oldest_listing", curve="taq_empirical"),
                     warmup=260)
    d = res.diagnostics
    assert d["cost_curve"] == "taq_empirical"
    assert d["n_name_fills_priced_by_curve"] == 8
    assert d["n_name_fills_curve_unpriceable"] == 0
    assert d["curve_unpriceable_fraction"] == 0.0
    # The measured branch is structurally unreachable from a permno panel and
    # the receipt SAYS so rather than implying TAQ priced these fills.
    mix = d["cost_curve_provenance_mix"]
    assert mix["MEASURED_TAQ_EFFECTIVE"] == 0
    assert mix["EXTRAPOLATED_REGRESSION"] == 8
    # Spread and impact are reported APART: collapsing them is how the two
    # become one word three call sites later.
    assert d["cost_curve_spread_usd"] > 0
    assert d["cost_curve_impact_usd"] >= 0
    assert (d["cost_curve_spread_usd"] + d["cost_curve_impact_usd"]
            == pytest.approx(d["total_cost_usd"], abs=0.02))
    assert d["mean_realised_cost_bps"] > 0
    assert d["cost_ratio_curve_over_flat"] > 0


def test_the_illiquid_tercile_costs_MORE_than_the_liquid_one():
    """Not a tautology: it is the sign of `b1` surviving the whole pipeline
    from the fit, through the replay's per-fill lookup, onto a receipt."""
    dv = np.array([2e6, 3e6, 4e6, 5e6, 3e8, 5e8, 9e8, 4e9])
    res = replay.run(_panel(dolvol=dv),
                     Policy(top_k=8, universe_n=8, holding_days=1000,
                            signal="oldest_listing", curve="taq_empirical"),
                     warmup=260)
    terciles = res.diagnostics["cost_bps_by_liquidity_tercile"]
    assert terciles["under_10m"]["one_way_bps"] > terciles["over_100m"]["one_way_bps"]
    assert res.diagnostics["liquidity_tercile_cuts_usd"] == [1e7, 1e8]


def test_a_name_the_curve_cannot_price_is_charged_the_DECLARED_rate_and_counted():
    """And it is NOT charged an end of the declared band --
    `cost_model.resolve_band_by_picking` is a named refusal, and a loop is the
    last place to start quietly picking ends."""
    p = _panel(dolvol=np.array([1e8] * 8))
    # VOLATILITY is the input that can genuinely be absent here: a name with
    # no dollar volume is already ineligible (`eligible_at` requires a finite
    # trailing dolvol), so the only way into the unpriceable branch is a
    # missing sigma -- which is what a name with too little history has.
    vol = np.full((T, 8), 0.01)
    vol[:, :4] = np.nan
    res = replay.run(p, Policy(top_k=8, universe_n=8, holding_days=1000,
                               signal="oldest_listing", curve="taq_empirical"),
                     vol=vol, warmup=260)
    d = res.diagnostics
    assert d["n_name_fills_curve_unpriceable"] == 4
    assert d["curve_unpriceable_fraction"] == 0.5


