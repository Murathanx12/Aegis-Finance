T = 420


def _strategy(**kw) -> Strategy:
    base = dict(
        strategy_id="test:book", title="a book", universe=Universe(name="u"),
        signal=Signal(name="mom_12_1"), construction=Construction(),
        hold=HoldRule(), sizing=Sizing(), costs=CostModel(),
        benchmark=Benchmark(), objective=Objective(),
        loss_budget=LossBudget(positions_judged=20, expected_losers=8))
    base.update(kw)
    return Strategy(**base)


def _panel(n_names: int = 8, ret: float = 0.0, dolvol=1e8) -> Panel:
    r = np.full((T, n_names), ret)
    tri = np.cumprod(1.0 + r, axis=0)
    close = 100.0 * tri
    dv = (np.full((T, n_names), float(dolvol)) if np.isscalar(dolvol)
          else np.tile(np.asarray(dolvol, dtype=float), (T, 1)))
    return Panel(
        dates=np.array([f"d{i:04d}" for i in range(T)], dtype=object),
        permnos=np.arange(1, n_names + 1, dtype=np.int64),
        close=close.astype(np.float32), open_=close.astype(np.float32),
        ret=r.astype(np.float32), retx=r.astype(np.float32),
        traded=np.ones((T, n_names), dtype=bool),
        dolvol=dv.astype(np.float32),
        mktcap=np.full((T, n_names), 1e10, dtype=np.float32),
        tri=tri.astype(np.float32), source="flat")


# ------------------------------------------------- identity: nothing moved

def test_adding_curve_changed_NO_existing_policy_id():
    """The whole point of `_HASH_NEUTRAL_DEFAULTS`. These hashes were taken
    from the code BEFORE the field existed; a `policy_id` is what tells a
    receipt and a rerun they are the same policy, and a field appended to a
    frozen dataclass changes every one of them unless it is dropped at its
    default."""
    assert Policy().policy_id == "6479736fde09f076"
    assert Policy(signal="mom_12_1", holding_days=5,
                  top_k=10).policy_id == "a07f8af3442df626"
    assert Policy(transaction_cost_bps=0.0, slippage_bps=0.0,
                  zero_cost_diagnostic=True).policy_id == "394a47ae22f5a61d"
    assert Policy(sizing="inverse_vol", universe_n=1000,
                  note="x").policy_id == "4c3465df467616b1"


def test_a_REAL_ARCHIVED_row_still_reproduces_its_own_policy_id():
    """The strongest available pin: a row written by a 2013-2024 farm run,
    reconstructed field by field, must still hash to the identity the receipt
    on disk records. A literal in a test can be regenerated by accident; an
    archived receipt cannot."""
    d = (Path(__file__).resolve().parents[1] / "data" / "optimus"
         / "portfolio_farm")
    receipts = sorted(d.glob("farm_*_2013_2024.json")) if d.exists() else []
    if not receipts:                                     # pragma: no cover
        pytest.skip("archived farm receipts not on disk")
    fields = set(Policy.__dataclass_fields__)
    n = renamed = 0
    for p in receipts:
        blob = json.loads(p.read_text(encoding="utf-8"))
        for rows in blob.values():
            if not (isinstance(rows, list) and rows
                    and isinstance(rows[0], dict) and "policy_id" in rows[0]):
                continue
            for row in rows:
                kw = {k: v for k, v in row.items() if k in fields}
                if "curve" in kw:                        # pragma: no cover
                    continue
                try:
                    pol = Policy(**kw)
                except PolicyError:
                    # A row whose SIGNAL was renamed in Aug 2026 is already
                    # unreconstructable and has been since that rename -- a
                    # pre-existing fact this test surfaces rather than causes.
                    renamed += 1
                    continue
                assert pol.policy_id == row["policy_id"], (
                    f"{p.name}: {row['label']}")
                n += 1
    assert n >= 1000, f"only {n} archived rows reconstructed"
    assert renamed < n / 10, (
        f"{renamed} archived rows are unreconstructable because their signal "
        f"was renamed; that is a separate, pre-existing problem, but at this "
        f"share it would hollow out this pin")


