@pytest.mark.parametrize("curve", ["flat", "taq_empirical", "retail_paper"])
def test_zero_cost_still_REFUSES_under_every_curve(curve, monkeypatch):
    """SPEC S4 ITEM 4. The refusal asks whichever ruler is declared: under a
    curve the two flat fields are unused, so a curve whose every rate happened
    to floor at exactly zero is the bug this catches."""
    from backend.services import cost_curve as CC

    if curve == "flat":
        with pytest.raises(PolicyError, match="zero transaction cost"):
            Policy(transaction_cost_bps=0.0, slippage_bps=0.0)
    else:
        Policy(curve=curve)                     # the real floor is positive
        monkeypatch.setattr(CC, "curve_floor_one_way_bps", lambda _c: 0.0)
        with pytest.raises(PolicyError, match="zero transaction cost"):
            Policy(curve=curve, transaction_cost_bps=0.0, slippage_bps=0.0)


