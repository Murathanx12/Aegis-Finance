# ------------------------------------------------------- the flat path held

def test_the_flat_path_is_UNCHANGED_to_the_cent():
    """The reserve/target refactor must be a no-op under `flat`, or every
    archived net silently stops reproducing. Same hand arithmetic as
    `test_a_flat_market_LOSES_exactly_the_costs`:
        deployed = 10,000 * (1 - 0.0012) = 9,988.00
        cost     = 9,988.00 * 0.0006     =     5.9928
    """
    res = replay.run(_panel(), Policy(top_k=5, universe_n=20,
                                      holding_days=1000,
                                      signal="oldest_listing"), warmup=260)
    assert res.nav[-1] == pytest.approx(10_000.0 - 5.9928, abs=1e-6)
    assert res.diagnostics["cost_curve"] == "flat"
    assert res.diagnostics["cost_curve_provenance"] == "flat_declared"
    assert res.diagnostics["mean_realised_cost_bps"] == pytest.approx(6.0)


