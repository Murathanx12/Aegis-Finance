def test_across_phases_does_not_merge_two_curves_into_one_median():
    from backend.services.portfolio_farm.farm import across_phases
    from backend.services.portfolio_farm.policy import FarmResult

    def _r(curve, terminal):
        pol = Policy(top_k=5, universe_n=20, curve=curve)
        return FarmResult(policy=pol, dates=["d"], nav=[1.0],
                          metrics={"status": "ok", "terminal_usd": terminal},
                          diagnostics={})

    out = across_phases([_r("flat", 1.0), _r("taq_empirical", 2.0)])
    assert len(out) == 2, "two curves collapsed into one row"
    assert {r["cost_curve"] for r in out} == {"flat", "taq_empirical"}
